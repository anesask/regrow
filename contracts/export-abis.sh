#!/usr/bin/env bash
# Export contract ABIs for the backend (JSON) and the app (typed TS consts for viem/wagmi).
set -euo pipefail
cd "$(dirname "$0")"
mkdir -p ../backend/chain ../app/src/lib/chain
forge build --silent
ts=../app/src/lib/chain/abis.ts
echo "// Generated by contracts/export-abis.sh. Do not edit." > "$ts"
for c in Filiz RestorationEscrow ImpactCertificate ReplantingPool RecoveryRegistry TimelockController; do
  forge inspect "$c" abi --json > "../backend/chain/$c.abi.json"
  printf 'export const %sAbi = %s as const\n\n' "$c" "$(cat "../backend/chain/$c.abi.json")" >> "$ts"
done
echo "ABIs written to backend/chain and app/src/lib/chain"
